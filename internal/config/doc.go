// Package config 解析、迁移与持久化 router-config.json。
//
// 讲清**为什么**这一层刻意保留了一些看起来可以简化的行为，以及工作空间的边界在
// 哪里。改了这里的约定之前，请先读完。
//
// # 兼容性契约
//
// 参照实现（Python）已退役。它当年留下的差分语料也随之一并删除，因此**现在没有**一份
// 外部 oracle 来锁住字节；本包的行为契约由自身的用例（`*_test.go`）与「不破坏既有配置
// 与既有调用方」这条要求共同承担。所以本包的目标仍是「字节级可用」而不是「设计得干净」：
//
//   - 字段顺序按插入顺序落盘（不排序），避免每次保存都重排整份文件；
//   - 整数与浮点分别渲染（60 与 60.0），与 canonical 包一致；
//   - 错误文本原样上报给管理 API 的调用方，属于对外契约，措辞不得改写；
//   - 迁移保留 v1/v2 的列表布局与 v3 的 pool 白名单语义，包括其中已知的怪异之处。
//
// 没有样本覆盖的输入**不做猜测式对齐**：要么失败关闭（InternalError），要么按
// 调用方给出的顺序取确定性的结果。宁可显式分叉，也不产出一份「碰巧对得上」的配置。
//
// # 顶层 upstream_routes 为什么被忽略
//
// 只由 providers[].routes 汇总而来。配置文件顶层的 upstream_routes 与 provider
// key 级的 upstream_routes 都会被忽略——这是参照实现的实际行为（config.py:877 从
// 空字典起步，而 KeyConfig 在 config.py:963 构造时未传 upstream_routes）。这是刻意
// 保留的历史语义，不是遗漏；改动它会让已有配置的输出发生变化。
//
// # 工作空间
//
// 工作空间（workspaces）是 Go 侧新增的能力，参照实现没有，因此这一部分**没有**
// 历史语义要沿用，它的兼容性契约是另一条：**不影响既有配置与既有调用方**。
//
//	config_version 仍是 4，workspaces 是可选新增字段，
//	顶层 tasks 就是 DefaultWorkspace。
//
// 由此推出几条必须保持的性质：
//
//   - 不带 X-AMKR-Workspace 头的请求行为逐字节不变。正因如此，
//     `tasks/list` 这类既有响应体**没有、也不允许**新增 workspace 字段——当前空间由
//     请求头决定，不体现在响应里。display_name 是唯一的例外，且**只在任务真的取了名时
//     才出现**：没取名的任务响应因此与改动前逐字节相同，既有调用方完全看不到这个字段。
//     理由是显示名属于任务本身（随导出/导入走），而不像「当前空间」那样是请求上下文。
//   - 工作空间**只隔离任务**。模型 ID、别名与 unified-model 仍然全局唯一，
//     任务名也不能与它们撞名（见 Validate）：否则 resolve_route 的语义会取决于查表
//     顺序，而那是全局唯一的判断，工作空间不能用来遮蔽模型名。
//   - 任务名只在同一工作空间内唯一。两个空间各有一个 summarize 是合法配置。
//   - 工作空间通常由「在它里面建任务」隐式产生，配置里的**无 key** 空分组会被清掉
//     （configops.writeWorkspaceTasks 删空即删分组）。WorkspaceNames 因此由任务反推
//     而不是回放配置键：一个没有成员的分组既不可观测也没有意义，两边口径必须相同，
//     否则界面上会出现一个删不掉的幽灵分组。
//   - **例外**：带 api_key 的工作空间（面板/嵌入方凭据，见 WorkspaceConfig）即使一个
//     任务都没有也会保留。这不是放松「空分组无意义」，而是那种空间有任务之外的**可
//     观测内容**——它自己就是一条凭据，删掉它等于悄悄吊销一个正在用的面板。两个口径
//     仍是同一条：writeWorkspaceTasks 只在 api_key 为空时删空分组，WorkspaceNames
//     把带 key 的空间一并列出。
//   - 未配置的工作空间名**不是错误**。那里没有任务，于是按普通模型名继续解析，最终
//     和「模型未配置」是同一个 404。单加一条「空间不存在」的错误既没有信息量，也会
//     多一种需要维护的状态。NormalizeWorkspace 只做去空白，不校验存在性。
//   - 手工构造 RouterConfig 的调用方（测试、内部装配）可以不管工作空间：Validate
//     会把零值 Workspace 归一成 DefaultWorkspace。
//
// 任务的 model 与 display_name 都是可选的（Go 侧放宽，参照实现里 model 必填）：
//
//   - model 缺失 / null / 空白串都归一成空串，表示「尚未指定模型」。任务可以先建出来
//     占位，被请求时由 proxy 明确报 404，**不做任何回落**——静默落到别的模型上会让一个
//     忘记选模型的任务照常服务，用户既看不到问题也无从知道自己调用的其实是另一个模型。
//   - 但「填了却填错」仍是错误：引用了未配置的模型照旧报「引用了未配置的模型」，否则
//     错字会静默退化成一个空任务。
//   - 有备选却没有首选是非法组合（备选无处可退）。这条不在 Validate 里查——校验顺序
//     与文案是对外契约，不能插入新分支——而是在 configops.CreateTask/UpdateTask 与
//     RepairTasks 里挡住/清掉。
//   - display_name 是纯展示用的中文名，两端空白在解析时清掉，不参与路由（调用方仍然
//     传 Name）。它随配置导出/导入一起走，因此放在配置里而不是浏览器本地。
//
// 需要「工作空间在配置里长什么样」的读者，请看 docs/USAGE.md 9.1；需要「调用方怎么
// 选空间」的，看 docs/API.md 的「任务路由 → 工作空间」。
//
// # 校验的顺序也是契约
//
// Validate 的错误顺序与措辞是对外契约（历史上对齐 config.py:1108）。新增检查时请追加在
// **末尾**或紧邻同类检查，不要插到既有检查之前——那会改变既有非法配置报出的第一条
// 错误，从而让已经依赖该顺序的调用方与用例一起失效。
